"""Пакетное закрытие просроченных уведомлений о расторжении.

Вторая половина правила «три дня». Первая — ленивая: срок закрывается на
первом же заходе человека в комнату (`services.finalize_expired_termination_for_user`).
Ленивого пути недостаточно: фрилансер может просто не открыть проект, а
слот и место в команде обязаны освободиться по сроку, а не по визиту.
Поэтому команда ставится в cron рядом с остальными периодическими задачами.

Своей выборки и своего понимания «просрочено» здесь нет: команда вызывает
доменный `termination.finalize_expired_terminations()` и печатает его
результат. Второе место, где живёт условие дедлайна, рано или поздно
разошлось бы с первым.

Запуск:

    python manage.py finalize_expired_terminations

Идемпотентна: уже завершённые и отозванные кейсы домен не выбирает,
`appeal_pending` не трогает никогда (у оспоренного кейса таймер остановлен),
и повторный запуск ничего не завершает повторно. Отсутствие просроченных
кейсов — обычный успешный исход, а не ошибка.
"""

from django.core.management.base import BaseCommand

from apps.rooms.termination import finalize_expired_terminations


class Command(BaseCommand):
    help = (
        'Завершает расторжения, по которым истёк срок ответа фрилансера '
        '(только notice_sent; оспоренные кейсы не трогает).'
    )

    def handle(self, *args, **options):
        finalized = finalize_expired_terminations()
        self.stdout.write(self.style.SUCCESS(
            f'Завершено просроченных расторжений: {finalized}.'
        ))
        return None
